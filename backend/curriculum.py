def _covered_by_longer_term(keyword: str, text: str) -> bool:
    """短词如果只出现在更长的课名里，就不单独认。例如「函数」出现在「二次函数」里。"""
    start = 0
    seen = False
    while True:
        index = text.find(keyword, start)
        if index < 0:
            break
        seen = True
        covered = False
        for term in _LONGER_TERMS:
            if len(term) <= len(keyword):
                continue
            place = text.find(term)
            while place >= 0:
                if place <= index < place + len(term):
                    covered = True
                    break
                place = text.find(term, place + 1)
            if covered:
                break
        if not covered:
            return False
        start = index + len(keyword)
    return seen


